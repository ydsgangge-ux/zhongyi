_locale = "zh"


def set_locale(locale: str):
    global _locale
    _locale = locale if locale in _locales else "zh"


def get_locale() -> str:
    return _locale


def t(key: str, **kwargs) -> str:
    text = _locales.get(_locale, {}).get(key, _locales["zh"].get(key, key))
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text
